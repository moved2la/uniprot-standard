"""composite.py on a synthetic pair of categories with hand-checkable numbers.

muscle: 3 kg of tissue at 200 g protein/kg -> 600 g protein; its profile is 4 % H.
blood:  a split table whose base row says 400 g protein; its profile is 10 % H.
Composite = 0.6 x muscle + 0.4 x blood -> H = 0.6 x 4 + 0.4 x 10 = 6.4. Every number is invented.
"""
