def _rows(path):
    return composite.read_commented_tsv(path)


def test_composite_is_the_protein_mass_weighted_mix(repo):
    assert composite.main([]) == 0
    out = repo / "outputs" / "composite"
    rows = {r["amino_acid"]: r for r in _rows(out / "_calculated_amino_acid_standard_composite.tsv")}
    assert float(rows["H"]["muscle"]) == pytest.approx(4.0)
    assert float(rows["H"]["blood"]) == pytest.approx(10.0)
    assert float(rows["H"]["composite"]) == pytest.approx(0.6 * 4 + 0.4 * 10)          # 600 g : 400 g
    assert sum(float(r["composite"]) for r in rows.values()) == pytest.approx(100.0, abs=1e-6)
    masses = {(r["category"], r["sex"]): r for r in _rows(out / "category_protein_masses.tsv")}
    assert float(masses[("muscle", "male")]["protein_g"]) == pytest.approx(600.0)     # 3000 g x 200 g/kg / 1000
    assert float(masses[("blood", "male")]["share_of_composite"]) == pytest.approx(0.4)
    assert float(masses[("muscle", "female")]["protein_g"]) == pytest.approx(400.0)
    assert float(masses[("blood", "female")]["protein_g"]) == pytest.approx(300.0)
    assert composite.main(["--check"]) == 0


def test_contributions_sum_to_the_composite_and_split_the_histidine(repo):
    composite.main([])
    rows = {r["amino_acid"]: r for r in _rows(repo / "outputs" / "composite" / "category_contributions.tsv")}
    h = rows["H"]
    assert float(h["g_from_muscle"]) == pytest.approx(2.4) and float(h["g_from_blood"]) == pytest.approx(4.0)
    assert float(h["fraction_from_blood"]) == pytest.approx(4.0 / 6.4)


def test_sensitivity_moves_the_mass_with_the_share(repo):
    """L3: the `other` row of the split puts blood at 250 g with a 20 % H profile:
    f_blood = 250 / 850, composite H = (600 x 4 + 250 x 20) / 850."""
    composite.main([])
    rows = _rows(repo / "outputs" / "composite" / "sensitivity_category_split.tsv")
    base = [r for r in rows if r["split_row"] == "as_measured" and r["sex"] == "male" and r["amino_acid"] == "H"][0]
    assert float(base["composite"]) == pytest.approx(6.4) and float(base["composite_minus_base"]) == pytest.approx(0.0)
    other = [r for r in rows if r["split_row"] == "other" and r["sex"] == "male" and r["amino_acid"] == "H"][0]
    assert float(other["category_protein_g"]) == pytest.approx(250.0)
    assert float(other["composite"]) == pytest.approx((600 * 4 + 250 * 20) / 850)
    female = [r for r in rows if r["split_row"] == "as_measured" and r["sex"] == "female" and r["amino_acid"] == "H"][0]
    assert float(female["composite"]) == pytest.approx((400 * 4 + 300 * 10) / 700)      # female masses, same profiles
    assert float(female["composite_minus_base"]) == pytest.approx(0.0)
    spread = {r["amino_acid"]: r for r in _rows(repo / "outputs" / "composite" / "sensitivity_category_split_spread.tsv")}
    assert float(spread["H"]["max"]) == pytest.approx((600 * 4 + 250 * 20) / 850)


def test_weighting_by_amino_acid_mass_uses_the_factor_and_the_pool(repo):
    """L4: every residue becomes 118/100 of itself, so both factors are 1.18; muscle adds the pool (0.005 g per g protein)."""
    composite.main([])
    cp = common.read_ini(repo / "outputs" / "composite" / "composite_summary.ini")
    wb = cp["weighting_basis"]
    assert float(wb["muscle_free_g_per_g_protein"]) == pytest.approx(1.18)
    assert float(wb["blood_free_g_per_g_protein"]) == pytest.approx(1.18)
    assert float(wb["muscle_pool_g_per_g_protein"].split(";")[0]) == pytest.approx(0.005)
    assert float(wb["muscle_amino_acid_mass_g"]) == pytest.approx(600 * (1.18 + 0.005))
    assert float(wb["blood_amino_acid_mass_g"]) == pytest.approx(400 * 1.18)
    assert float(cp["histidine"]["composite_g_per_100g"]) == pytest.approx(6.4)
    assert float(cp["masses"]["total_protein_g"]) == pytest.approx(1000.0)


def test_a_profile_that_does_not_sum_to_one_hundred_stops(repo):
    p = repo / "outputs" / "blood" / "blood.tsv"
    p.write_text(p.read_text().replace("10.000000", "12.000000"))
    with pytest.raises(SystemExit, match="sums to"):
        composite.main([])


def test_a_basis_mismatch_stops(repo):
    p = repo / "config" / "pools.ini"
    p.write_text(p.read_text().replace("basis = wet", "basis = dry"))
    with pytest.raises(SystemExit, match="basis"):
        composite.main([])


def test_one_category_is_not_a_composite(repo):
    p = repo / "config" / "tissue_mass_fractions.ini"
    text = p.read_text()
    p.write_text(text[:text.index("[category.blood]")])
    with pytest.raises(SystemExit, match="at least two"):
        composite.main([])
