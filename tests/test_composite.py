from pipeline import common, composite

AA = list(common.AMINO_ACIDS)


def _profile(hi: str, val: float) -> dict[str, float]:
    p = {a: (100 - val) / 19 for a in AA}
    p[hi] = val
    return p


def _table(path, column, prof, extra_cols=()):
    hdr = ["amino_acid"] + list(extra_cols) + [column]
    rows = [[a] + ["x"] * len(extra_cols) + [f"{prof[a]:.6f}"] for a in AA]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("# GENERATED by test\n# generated = t\n" + "\t".join(hdr) + "\n" + "\n".join("\t".join(r) for r in rows) + "\n")


